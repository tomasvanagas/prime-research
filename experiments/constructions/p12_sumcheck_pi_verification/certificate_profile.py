#!/usr/bin/env python3
"""
certificate_profile.py -- S509.  Characterize the FULL non-interactive certificate
for "pi(x) = c" and LOCATE the Õ(sqrt x) communication wall.

CONTEXT.  By S508 the whole-chain VERIFIER's expensive sub-term -- the count of
large-table (mle_eval over a sqrt-x-size cube) evaluations -- is Õ(x^{1/4}) (the
two S_0 base closes go through the tensor PCS; every per-layer leaf open was
removed by pcs+batch_trace+batch_ub).  The verifier side of the milestone is met.
The quantity that is STILL Õ(sqrt x) is the certificate SIZE itself: stats["comm"]
(the Fiat-Shamir transcript) has slope ~0.5 in every config.  This file pins down
exactly WHERE that Õ(sqrt x) lives.

WHAT IS MEASURED (full succinct config = delegate+structured+pcs+batch_trace+
batch_ub+batch_wiring+commit_base, over n in {8..18}):
  (i)   certificate SIZE = total stats["comm"] in field elements AND in bits
        (bits = elems * ceil(log2 q); BIG_Q elems are 61-bit, Q elems 31-bit --
        a constant factor, same exponent);
  (ii)  verifier op-count = vleaf_ops_pl + vleaf_ops_ot (== vcommit_ops in this
        config -- the only LARGE-table work left is the one-time PCS base opens);
  (iii) prover wall.
Each exponent is fitted (alpha = d log2(metric) / d n, so alpha~1 => Theta(x),
alpha~0.5 => Theta(sqrt x), alpha~0.25 => Theta(x^{1/4})).

The full config STRICTLY EXTENDS the S508 "config (d)" named in PROGRAM.md by also
turning on batch_wiring (built S503/S504 precisely to cut comm ~5x): with the
wiring batched, comm_outer is PURELY the sequential two-sided layer reductions, the
cleanest form of the result.  We also print the no-batch_wiring variant to show the
conclusion is robust either way (there the batchable wiring is merely folded into
comm_outer, making it even more dominant).

ATTRIBUTION.  run_chain (S509) partitions stats["comm"] by source -- a purely
additive boundary-snapshot, transcript unchanged:
  comm_outer : the K = pi(sqrt x) SEQUENTIAL per-layer two-sided reductions
               (phase-A/phase-B outer sum-checks + the pcs line/claim folds).
  comm_bt    : the ONE batched trace zero-test (all K layers).
  comm_bw    : the ONE batched wiring discharge (all 2K-1 wirings).
  comm_ub    : the ONE batched Ub-opening discharge (all K*nb leaves).
  comm_base  : the two one-time S_0 closes (tensor-PCS eval proofs).
The five sum EXACTLY to stats["comm"] (asserted).

HEADLINE RESULT.  The Õ(sqrt x) certificate is DOMINATED by comm_outer (60% -> 90%
of the total as n: 8 -> 18, and -> 100% asymptotically): after EVERY batchable
obligation has been batched (trace/wiring/Ub -> polylog) and the base committed
(-> x^{1/4}), the only term left at Theta(sqrt x) is the K sequential layer
reductions.  comm_outer ~ K * nb^2 = pi(sqrt x) * O(log^2 x) = Theta(sqrt x polylog).

MEMBERSHIP STATEMENT this yields.  L_pi = {(x,c) : pi(x) = c} has, under a
collision-resistant-hash / random-oracle assumption (Fiat-Shamir of the chain), a
NON-INTERACTIVE certificate of size Õ(sqrt x) field elements (Õ(sqrt x * log^2 x)
bits), whose expensive (large-table) verifier work is Õ(x^{1/4}).  HONEST: the
verifier must READ the Õ(sqrt x) proof (each transcript scalar is an O(1) sum-check
round check), so TOTAL verification is Theta(sqrt x) -- bounded below by the proof
size.  The Õ(x^{1/4}) of S508 is the large-table-eval SUB-term only; this file makes
that explicit.  Compressing the SIZE (and hence total verification) below sqrt x to
polylog requires batching the K SEQUENTIAL outer reductions -- which hits the SAME
wall as open item 2 (the layer-batching closed negative): each layer's OUTPUT claim
is the next layer's INPUT claim, a dependency chain, unlike the trace/Ub/wiring
obligations (independent per-layer witnesses sharing one random trajectory, hence
batchable).  The semigroup generated by v |-> floor(v/p) is the precise obstruction.

FALSIFIERS (any one would break the result):
  * total comm exponent NOT ~0.5 (we assert it lands in [0.4, 0.65]);
  * the per-source attribution NOT summing to the measured comm (asserted exactly);
  * comm_outer NOT the dominant / growing fraction, or its exponent NOT ~0.5;
  * the batched-discharge / base exponents NOT sub-0.5 (they should be polylog or
    x^{1/4});
  * verifier-op exponent NOT ~0.25 (re-confirms S508);
  * claimed pi(x) differing from the sieve in any config / field;
  * a claimed batching of the SEQUENTIAL outer reductions that actually drops the
    comm exponent below 0.5 -- that would be a genuine breakthrough (it batches the
    floor(v/p) semigroup), NOT a measurement; verify it against open item 2 before
    believing it.

CLI:
  python3 certificate_profile.py --selftest
  python3 certificate_profile.py                 # the profile (default q, n=8..18)
  python3 certificate_profile.py --field big     # over BIG_Q=2^61-1 (61-bit elems)
"""
import argparse
import math
import time

import numpy as np

import compressed_layer as cl

# the minimal certificate: every batchable obligation batched, base committed.
FULL = dict(delegate=True, structured=True, pcs=True, batch_trace=True,
            batch_ub=True, batch_wiring=True, commit_base=True)
# the literal S508 "config (d)" -- wiring NOT batched (discharged inline per layer).
NOBW = dict(delegate=True, structured=True, pcs=True, batch_trace=True,
            batch_ub=True, commit_base=True)

COMM_SRCS = ["comm_outer", "comm_bt", "comm_bw", "comm_ub", "comm_base"]
FIELDS = {"q": cl.Q, "big": cl.BIG_Q}


def _verifier_ops(r):
    """Large-table (mle_eval / PCS) field-op count -- the S507/S508 metric."""
    return r["vleaf_ops_pl"] + r["vleaf_ops_ot"]


def measure(ns, cfg, q, seed=1, check_truth=True):
    """Run run_chain over ns with cfg; return {n: result} (result carries an
    added 'wall' and 'x').  Asserts accept, claimed==sieve, and that the comm
    attribution sums exactly to stats['comm']."""
    out = {}
    for n in ns:
        x = (1 << n) - 1
        t = time.perf_counter()
        r = cl.run_chain(x, np.random.default_rng(seed), q=q, **cfg)
        r["wall"] = time.perf_counter() - t
        r["x"] = x
        if check_truth:
            assert r["accepted"], (n, "rejected honest run")
            assert r["claimed"] == cl.sieve_pi(x), (n, r["claimed"])
        # attribution closes exactly
        parts = sum(r[k] for k in COMM_SRCS)
        assert parts == r["comm"], (n, "comm attribution gap", parts, r["comm"])
        out[n] = r
    return out


def _fit(ns, vals):
    return cl._fit_slope(list(ns), [math.log2(max(1, v)) for v in vals])


def profile(ns=(8, 10, 12, 14, 16, 18), field="q", seed=1):
    q = FIELDS[field]
    bpe = q.bit_length()                       # bits per field element (31 / 61)
    print(f"=== certificate profile (full succinct config), field={field} "
          f"({bpe}-bit elems) ===")
    print("config = delegate+structured+pcs+batch_trace+batch_ub+batch_wiring"
          "+commit_base")
    data = measure(ns, FULL, q, seed)

    # ---- table 1: size / verifier ops / prover wall ----
    print("\n-- certificate SIZE, VERIFIER ops, PROVER wall --")
    print(f"{'n':>3} {'x':>9} {'V':>6} {'nb':>3} {'K':>4} {'pi':>7} | "
          f"{'cert_elems':>10} {'cert_KB':>8} | {'verif_ops':>9} | "
          f"{'prover_s':>8}")
    for n in ns:
        r = data[n]
        x = r["x"]; V = cl.isqrt(x); nb = max(1, V.bit_length()); K = r["layers"]
        kb = r["comm"] * bpe / 8 / 1024
        print(f"{n:>3} {x:>9} {V:>6} {nb:>3} {K:>4} {r['claimed']:>7} | "
              f"{r['comm']:>10} {kb:>8.2f} | {_verifier_ops(r):>9} | "
              f"{r['wall']:>8.3f}")

    # ---- table 2: per-source comm attribution ----
    print("\n-- comm ATTRIBUTION by source (field elements; outer = the K "
          "sequential layer reductions) --")
    print(f"{'n':>3} {'comm':>8} | {'outer':>8} {'out%':>5} | {'bt':>5} "
          f"{'bw':>6} {'ub':>5} {'base':>6}")
    for n in ns:
        r = data[n]
        pct = 100.0 * r["comm_outer"] / r["comm"]
        print(f"{n:>3} {r['comm']:>8} | {r['comm_outer']:>8} {pct:>4.0f}% | "
              f"{r['comm_bt']:>5} {r['comm_bw']:>6} {r['comm_ub']:>5} "
              f"{r['comm_base']:>6}")

    # ---- table 3: effect of batching the wiring (full vs S508 config (d)) ----
    print("\n-- comm: full (wiring batched) vs S508 config (d) (wiring inline) --")
    dnobw = measure(ns, NOBW, q, seed)
    print(f"{'n':>3} {'full_comm':>9} {'full_outer':>11} || "
          f"{'d_comm':>8} {'d_outer':>8}  (inline wiring folds into outer)")
    for n in ns:
        print(f"{n:>3} {data[n]['comm']:>9} {data[n]['comm_outer']:>11} || "
              f"{dnobw[n]['comm']:>8} {dnobw[n]['comm_outer']:>8}")

    # ---- exponent fits ----
    last = ns[-4:]
    print(f"\n-- fitted exponents alpha (metric ~ x^alpha; log2(metric) vs n, "
          f"last {len(last)} pts: n in {tuple(last)}) --")
    fits = {}
    rows = [
        ("comm (cert size)", [data[n]["comm"] for n in last], "~0.5  Theta(sqrt x)"),
        ("  comm_outer",     [data[n]["comm_outer"] for n in last], "~0.5  Theta(sqrt x)  <-- DOMINANT"),
        ("  comm_bt",        [data[n]["comm_bt"] for n in last], "polylog (sub-0.5)"),
        ("  comm_bw",        [data[n]["comm_bw"] for n in last], "polylog (sub-0.5)"),
        ("  comm_ub",        [data[n]["comm_ub"] for n in last], "polylog (sub-0.5)"),
        ("  comm_base",      [data[n]["comm_base"] for n in last], "~0.25 Theta(x^1/4) PCS"),
        ("verifier ops",     [_verifier_ops(data[n]) for n in last], "~0.25 Theta(x^1/4)"),
        ("prover wall",      [data[n]["wall"] for n in last], "see note"),
    ]
    print(f"{'metric':>20} {'alpha':>7}   expectation")
    for name, vals, exp in rows:
        a = _fit(last, vals)
        fits[name.strip()] = a
        print(f"{name:>20} {a:>7.3f}   {exp}")
    print("\nNOTE prover wall: measured alpha is overhead/call-count-bound "
          "(~sqrt x polylog;\n  S500/S501) at reachable n -- the asymptotic "
          "element-work is Õ(x) (S496/S497),\n  surfacing only past the "
          "array-size crossover.  Cert SIZE is the headline, not wall.")

    # ---- headline + falsifiable assertions ----
    a_comm = fits["comm (cert size)"]
    a_outer = fits["comm_outer"]
    a_ver = fits["verifier ops"]
    out_frac = [data[n]["comm_outer"] / data[n]["comm"] for n in ns]
    assert 0.40 <= a_comm <= 0.65, ("comm exponent not ~sqrt x", a_comm)
    assert 0.40 <= a_outer <= 0.65, ("comm_outer exponent not ~sqrt x", a_outer)
    assert a_ver < 0.35, ("verifier-op exponent not ~x^1/4", a_ver)
    for nm in ("comm_bt", "comm_bw", "comm_ub", "comm_base"):
        assert fits[nm] < a_outer, (nm, "not sub-dominant to outer", fits[nm], a_outer)
    assert out_frac[-1] > out_frac[0] and out_frac[-1] >= 0.80, \
        ("outer not the dominant / growing fraction", out_frac)
    print(f"\nHEADLINE: certificate SIZE alpha = {a_comm:.3f} ~ 0.5 "
          f"(Theta(sqrt x)); it is DOMINATED by the K SEQUENTIAL outer layer "
          f"reductions\n  (comm_outer alpha = {a_outer:.3f}, {100*out_frac[-1]:.0f}% "
          f"of comm at n={ns[-1]}, rising to 100%).  Every batchable obligation is "
          f"polylog;\n  the base commit is Theta(x^1/4); verifier large-table ops "
          f"alpha = {a_ver:.3f} ~ 0.25.\n  => L_pi has a CRH-based non-interactive "
          f"certificate of size Õ(sqrt x), verifiable with\n  Õ(x^1/4) large-table "
          f"opens (total verification Theta(sqrt x): the verifier reads the proof).\n"
          f"  The residual Õ(sqrt x) IS the floor(v/p)-semigroup sequential-layer "
          f"wall (open item 2).")
    return data


def selftest():
    print("[selftest] certificate_profile (S509)")
    rng = np.random.default_rng

    # 1. attribution sums EXACTLY to comm on COMPLETE (accepting) certificates --
    #    full, NOBW, and plain configs, over q AND BIG_Q.  Cheats (delta_pi,
    #    self-consistent liar) must still REJECT with the instrumentation present
    #    (a rejected transcript bails mid-layer, so partial comm is NOT a complete
    #    certificate and is not asserted to close -- by design).
    cfgs = {"full": FULL, "nobw": NOBW,
            "plain": dict(delegate=True, structured=True)}
    for n in (8, 10, 12):
        x = (1 << n) - 1; truth = cl.sieve_pi(x)
        K = len(cl.compressed_lucy(x)[0])
        for q in (cl.Q, cl.BIG_Q):
            for name, cfg in cfgs.items():
                r = cl.run_chain(x, rng(1), q=q, **cfg)
                assert r["accepted"] and r["claimed"] == truth, (name, n, q)
                assert sum(r[k] for k in COMM_SRCS) == r["comm"], (name, n, q, "sum")
                # cheats: the run must REJECT (instrumentation is inert to verdict)
                rd = cl.run_chain(x, rng(1), q=q, cheat="delta_pi", **cfg)
                assert not rd["accepted"], (name, n, q, "delta_pi accepted")
                i0 = max(1, K // 2)
                rl = cl.run_chain(x, rng(1), q=q, corrupt_layer=i0, **cfg)
                assert not rl["accepted"], (name, n, q, "liar accepted")
    print("  1. attribution closes on complete certs (full/nobw/plain, q & BIG_Q);"
          " cheats reject OK")

    # 2. comm COUNT (field elements) is field-independent (only bit-width differs);
    #    per-source counts match between q and BIG_Q too.
    for n in (8, 10, 12):
        x = (1 << n) - 1
        rq = cl.run_chain(x, rng(2), q=cl.Q, **FULL)
        rb = cl.run_chain(x, rng(2), q=cl.BIG_Q, **FULL)
        assert rq["comm"] == rb["comm"], (n, "comm count field-dependent")
        for k in COMM_SRCS:
            assert rq[k] == rb[k], (n, k, "per-source count field-dependent")
    print("  2. comm COUNT field-independent (q vs BIG_Q identical) OK")

    # 3. with wiring batched, comm_outer is purely the outer reductions and is
    #    STRICTLY less than the NOBW config's comm_outer (which folds the inline
    #    wiring in) -- the batching demonstrably moves comm out of 'outer'.
    for n in (10, 12):
        x = (1 << n) - 1
        rf = cl.run_chain(x, rng(3), q=cl.Q, **FULL)
        rd = cl.run_chain(x, rng(3), q=cl.Q, **NOBW)
        assert rf["comm_outer"] < rd["comm_outer"], (n, rf["comm_outer"], rd["comm_outer"])
        assert rf["comm_bw"] > 0 and rd["comm_bw"] == 0, n     # bw only in full
        assert rf["comm"] < rd["comm"], (n, "batching wiring did not cut comm")
    print("  3. batch_wiring moves comm out of 'outer' and cuts total comm OK")

    # 4. exponents on a short sweep (n=8..16): comm ~0.5, comm_outer ~0.5 and
    #    dominant+growing, batched discharges + verifier ops sub-0.4.
    ns = (8, 10, 12, 14, 16)
    data = measure(ns, FULL, cl.Q, seed=1)
    last = ns[-4:]
    a_comm = _fit(last, [data[n]["comm"] for n in last])
    a_outer = _fit(last, [data[n]["comm_outer"] for n in last])
    a_bw = _fit(last, [data[n]["comm_bw"] for n in last])
    a_ver = _fit(last, [_verifier_ops(data[n]) for n in last])
    frac = [data[n]["comm_outer"] / data[n]["comm"] for n in ns]
    assert 0.40 <= a_comm <= 0.65, a_comm
    assert 0.40 <= a_outer <= 0.65, a_outer
    assert a_bw < 0.40 and a_bw < a_outer, (a_bw, a_outer)
    # verifier large-table ops grow STRICTLY slower than the cert size (sub-sqrt-x);
    # the tight ~0.25 (Theta(x^1/4)) only settles past nb~14 (n~28, S508) -- on this
    # short sweep the t-query / reshape constant still inflates it, so bound loosely.
    assert a_ver < a_comm and a_ver < 0.45, (a_ver, a_comm)
    assert frac[-1] > frac[0] and frac[-1] >= 0.80, frac
    print(f"  4. exponents OK (comm {a_comm:.2f}, outer {a_outer:.2f} dom "
          f"{100*frac[-1]:.0f}%, bw {a_bw:.2f}, verif {a_ver:.2f})")

    # 5. verifier large-table ops in the full config are ENTIRELY one-time (the
    #    PCS base opens): per-layer leaf count 0, ops == vcommit_ops.
    for n in (8, 12, 16):
        x = (1 << n) - 1
        r = cl.run_chain(x, rng(4), q=cl.Q, **FULL)
        assert r["vleaf_cnt_pl"] == 0, (n, r["vleaf_cnt_pl"])
        assert r["vleaf_ops_pl"] == 0, (n, r["vleaf_ops_pl"])
        assert r["vcommit_ops"] == r["vleaf_ops_ot"] > 0, (n,)
    print("  5. verifier large-table work is one-time only (vleaf_pl=0) OK")

    print("[selftest] PASS")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--selftest", action="store_true")
    ap.add_argument("--field", choices=list(FIELDS), default="q",
                    help="prime field: q=2^31-1 (31-bit), big=2^61-1 (61-bit)")
    ap.add_argument("--nmax", type=int, default=18, help="largest n (even)")
    ap.add_argument("--seed", type=int, default=1)
    args = ap.parse_args()
    if args.selftest:
        selftest()
    else:
        ns = tuple(range(8, args.nmax + 1, 2))
        profile(ns, field=args.field, seed=args.seed)


if __name__ == "__main__":
    main()
